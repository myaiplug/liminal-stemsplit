#!/usr/bin/env python3
"""Single source of truth for the app version.

The version lives in ``VERSION`` (app root, next to package.json). This script
writes it into every place that needs it:

  - package.json + package-lock.json (root package entry)
  - src-tauri/tauri.conf.json (version + window title)
  - src-tauri/Cargo.toml + the stemsplit entry in Cargo.lock
  - setup.iss / setup_online.iss (AppVersion + output file name)
  - src/lib/app-version.ts, src/lib/analytics.ts, src/lib/site-warmup.ts
  - scripts/version.py and scripts/VERSION (bundled with the app so the
    Python engine and model_doctor can read it)
  - release download links in src/components/ReactorZone.tsx

Usage:
    python scripts/sync_version.py            # write 0.x.y from VERSION everywhere
    python scripts/sync_version.py 0.7.1      # set VERSION first, then sync
    python scripts/sync_version.py --check    # exit 1 if anything is out of sync (CI)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
SEMVER = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$")
ANY_VER = r"\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?"


def _read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def _sub(text: str, pattern: str, repl, count: int = 0, flags: int = 0):
    new, n = re.subn(pattern, repl, text, count=count, flags=flags)
    return new, n


def build_targets(v: str):
    """Yield (relative path, function(text)->(new_text, replacements))."""
    def package_json(t):
        return _sub(t, r'^(\s*"version":\s*")' + ANY_VER + '(")', rf"\g<1>{v}\g<2>", count=1, flags=re.M)

    def package_lock(t):
        # first two "version" keys: top-level and packages[""]
        data = json.loads(t)
        data["version"] = v
        if "" in data.get("packages", {}):
            data["packages"][""]["version"] = v
        out = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
        return out, 1

    def tauri_conf(t):
        t, n1 = _sub(t, r'^(\s*"version":\s*")' + ANY_VER + '(")', rf"\g<1>{v}\g<2>", count=1, flags=re.M)
        t, n2 = _sub(t, r"(StemSplit v)" + ANY_VER, rf"\g<1>{v}")
        return t, n1 + n2

    def cargo_toml(t):
        return _sub(t, r'^(version\s*=\s*")' + ANY_VER + '(")', rf"\g<1>{v}\g<2>", count=1, flags=re.M)

    def cargo_lock(t):
        return _sub(t, r'(\[\[package\]\]\nname = "stem-split"\nversion = ")' + ANY_VER + '(")', rf"\g<1>{v}\g<2>", count=1)

    def iss(t):
        t, n1 = _sub(t, r'(#define MyAppVersion ")' + ANY_VER + '(")', rf"\g<1>{v}\g<2>")
        t, n2 = _sub(t, r"(Setup-v)" + ANY_VER + r"(-Windows)", rf"\g<1>{v}\g<2>")
        return t, n1 + n2

    def app_version_ts(t):
        return _sub(t, r"(APP_VERSION\s*=\s*')" + ANY_VER + "(')", rf"\g<1>{v}\g<2>")

    def analytics_ts(t):
        return _sub(t, r"(version:\s*')" + ANY_VER + "(')", rf"\g<1>{v}\g<2>")

    def reactor(t):
        t, n1 = _sub(t, r"(releases/download/v)" + ANY_VER + r"(/)", rf"\g<1>{v}\g<2>")
        t, n2 = _sub(t, r"(NoDAW\.Liminal_)" + ANY_VER + "(_x64-setup)", rf"\g<1>{v}\g<2>")
        t, n3 = _sub(t, r"(Setup-v)" + ANY_VER + r"(-Windows)", rf"\g<1>{v}\g<2>")
        t, n4 = _sub(t, r"(font-mono\">v)" + ANY_VER + "(</span>)", rf"\g<1>{v}\g<2>")
        return t, n1 + n2 + n3 + n4

    def version_py(t):
        return f'"""Generated by sync_version.py - do not edit. Edit ../VERSION instead."""\n__version__ = "{v}"\n', 1

    def version_file(t):
        return v + "\n", 1

    return [
        ("package.json", package_json),
        ("package-lock.json", package_lock),
        ("src-tauri/tauri.conf.json", tauri_conf),
        ("src-tauri/Cargo.toml", cargo_toml),
        ("src-tauri/Cargo.lock", cargo_lock),
        ("setup.iss", iss),
        ("setup_online.iss", iss),
        ("src/lib/app-version.ts", app_version_ts),
        ("src/lib/analytics.ts", analytics_ts),
        ("src/lib/site-warmup.ts", analytics_ts),
        ("src/components/ReactorZone.tsx", reactor),
        ("scripts/version.py", version_py),
        ("scripts/VERSION", version_file),
    ]


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if not a.startswith("--")]
    vfile = APP / "VERSION"
    if args:
        if not SEMVER.match(args[0]):
            print(f"not a semver: {args[0]}", file=sys.stderr)
            return 2
        vfile.write_text(args[0] + "\n", encoding="utf-8")
    v = _read(vfile).strip()
    if not SEMVER.match(v):
        print(f"VERSION file has invalid semver: {v!r}", file=sys.stderr)
        return 2

    bad = []
    for rel, fn in build_targets(v):
        p = APP / rel
        old = _read(p) if p.exists() else ""
        if not p.exists() and not rel.startswith("scripts/"):
            print(f"  skip (missing): {rel}")
            continue
        new, n = fn(old)
        if n == 0:
            bad.append(f"{rel}: pattern not found")
            continue
        if new != old:
            if check:
                bad.append(f"{rel}: out of sync with VERSION {v}")
            else:
                p.write_text(new, encoding="utf-8")
                print(f"  updated {rel}")
    if bad:
        for b in bad:
            print("ERROR", b, file=sys.stderr)
        return 1
    print(f"version {v}: {'in sync' if check else 'synced'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
